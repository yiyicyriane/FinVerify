"""Offline tests for data/clean_filing.py using synthetic Inline XBRL fixtures.

The fixtures copy the layout quirks of the real filings (no network needed):
  * Apple: table of contents, MD&A with a ready-made gross margin %, statement index,
    hidden ix:header, unit note above the table, "$ | 1,234 | )" cells under a
    colspan year header
  * MSFT: headings without "Consolidated", unit note inside the table, a
    "COMPREHENSIVE INCOME STATEMENTS" table between income statement and balance sheet
  * HD: "Statements of Earnings", balance sheet split across two <table>s

Run from repo root:  python -m unittest data.test_clean_filing -v
"""

