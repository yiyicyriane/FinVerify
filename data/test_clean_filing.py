HEAD = ('<?xml version="1.0" encoding="utf-8"?><!-- Workiva -->'
        '<html xmlns="http://www.w3.org/1999/xhtml" xmlns:ix="http://www.xbrl.org/2013/inlineXBRL" '
        'xmlns:us-gaap="http://fasb.org/us-gaap/2025"><head><title>x</title></head><body>'
        '<div style="display:none"><ix:header><ix:hidden>'
        '<ix:nonNumeric name="dei:AmendmentFlag" contextRef="c-1">false</ix:nonNumeric>'
        '</ix:hidden><ix:resources><xbrli:context id="c-1"/></ix:resources></ix:header></div>')
TAIL = "</body></html>"


def nf(v, tag="Assets", ctx="c-1"):
    return (f'<ix:nonFraction unitRef="usd" contextRef="{ctx}" decimals="-6" scale="6" '
            f'name="us-gaap:{tag}" format="ixt:num-dot-decimal">{v}</ix:nonFraction>')


def money_row(label, cur, prior, neg=False):
    """Typical SEC row: label | spacer | $ | value | ) | spacer | $ | value | )"""
    o, c = ("(", ")") if neg else ("", "")
    return (f'<tr><td><span>{label}</span></td><td>&#160;</td><td>$</td><td>{o}{nf(cur)}</td>'
            f'<td>{c}</td><td></td><td>$</td><td>{o}{nf(prior, ctx="c-2")}</td><td>{c}</td></tr>')


def header_row(cur, prior):
    return (f'<tr><td></td><td></td><td colspan="3"><span>{cur}</span></td><td></td>'
            f'<td colspan="3">{prior}</td></tr>')


